SERVER_RULE_QUESTIONS = [
    item
    for ordinal, item in enumerate(SERVER_RULE_QUESTIONS, start=1)
    if ordinal not in _OMITTED_SOURCE_ORDINALS
]


for index, item in enumerate(SERVER_RULE_QUESTIONS, start=1):
    item["id"] = index
    item["source_quote"] = RULE_SOURCE_QUOTES[item["rule"]]
    if not 3 <= len(item["options"]) <= 6:
        raise RuntimeError(f"Question {index}: expected 3-6 options")
    if not 1 <= len(item["correct"]) <= len(item["options"]):
        raise RuntimeError(f"Question {index}: invalid correct answer count")
    if len(set(item["correct"])) != len(item["correct"]):
        raise RuntimeError(f"Question {index}: duplicate correct answer")
    if any(
        type(answer) is not int or not 0 <= answer < len(item["options"])
        for answer in item["correct"]
    ):
        raise RuntimeError(f"Question {index}: invalid correct answer index")
    item["correct_text"] = tuple(
        f"{answer + 1}. {item['options'][answer]}" for answer in item["correct"]
    )

if len(SERVER_RULE_QUESTIONS) != 100:
    raise RuntimeError(
        f"Expected 100 server-rule questions, got {len(SERVER_RULE_QUESTIONS)}"
    )


RULE_DIFFICULTIES = ("Лёгкий", "Средний", "Сложный", "Ситуация")


class ServerRuleQuestion(Base):
    """Editable copy of a quiz question; the Python list is only the initial seed."""

    __tablename__ = "server_rule_questions"

    id = Column(Integer, primary_key=True, autoincrement=True)
    position = Column(Integer, nullable=False, index=True)
    rule = Column(String(32), nullable=False)
    difficulty = Column(String(32), nullable=False)
    question_text = Column(Text, nullable=False)
    options_json = Column(Text, nullable=False)
    correct_json = Column(Text, nullable=False)
    explanation = Column(Text, nullable=False)
    source_quote = Column(Text, nullable=True)
    created_at = Column(DateTime, nullable=False)
    updated_at = Column(DateTime, nullable=False)
    updated_by = Column(String(20), nullable=True)


def utcnow():
    return datetime.now(timezone.utc).replace(tzinfo=None)


def normalize_question_payload(payload):
    """Validate browser input and return a canonical question dictionary."""
    if not isinstance(payload, dict):
        raise ValueError("Ожидается объект с вопросом")

    rule = str(payload.get("rule") or "").strip()
    difficulty = str(payload.get("difficulty") or "").strip()
    text_value = str(payload.get("text") or "").strip()
    explanation = str(payload.get("explanation") or "").strip()
    options_value = payload.get("options")
    correct_value = payload.get("correct")

    if not rule or len(rule) > 32:
        raise ValueError("Укажите номер правила длиной до 32 символов")
    if difficulty not in RULE_DIFFICULTIES:
        raise ValueError("Выберите допустимую сложность")
    if not text_value or len(text_value) > 1000:
        raise ValueError("Введите вопрос длиной до 1000 символов")
    if not explanation or len(explanation) > 2000:
        raise ValueError("Введите пояснение длиной до 2000 символов")
    source_quote = str(
        payload.get("source_quote") or RULE_SOURCE_QUOTES.get(rule) or ""
    ).strip()
    if not source_quote or len(source_quote) > 5000:
        raise ValueError(
            "Добавьте цитату из указанного пункта правил длиной до 5000 символов"
        )
    if not isinstance(options_value, list) or not 3 <= len(options_value) <= 6:
        raise ValueError("У вопроса должно быть от 3 до 6 вариантов ответа")

    options = [str(value or "").strip() for value in options_value]
    if any(not value or len(value) > 500 for value in options):
        raise ValueError("Каждый вариант должен содержать от 1 до 500 символов")
    if len({value.casefold() for value in options}) != len(options):
        raise ValueError("Варианты ответа не должны повторяться")
    if not isinstance(correct_value, list) or not correct_value:
        raise ValueError("Отметьте хотя бы один правильный вариант")
    if any(type(index) is not int for index in correct_value):
        raise ValueError("Некорректный номер правильного варианта")
    correct = sorted(correct_value)
    if len(set(correct)) != len(correct) or any(
        index < 0 or index >= len(options) for index in correct
    ):
        raise ValueError("Некорректный набор правильных вариантов")

    return {
        "rule": rule,
        "difficulty": difficulty,
        "text": text_value,
        "options": options,
        "correct": correct,
        "explanation": explanation,
        "source_quote": source_quote,
    }


def question_record(row):
    options = json.loads(row.options_json)
    correct = json.loads(row.correct_json)
    return {
        "id": row.id,
        "rule": row.rule,
        "difficulty": row.difficulty,
        "text": row.question_text,
        "options": options,
        "correct": correct,
        "correct_text": [f"{index + 1}. {options[index]}" for index in correct],
        "explanation": row.explanation,
        "source_quote": row.source_quote or RULE_SOURCE_QUOTES.get(row.rule, ""),
    }


def apply_question(row, values, actor_id=None):
    row.rule = values["rule"]
    row.difficulty = values["difficulty"]
    row.question_text = values["text"]
    row.options_json = json.dumps(values["options"], ensure_ascii=False)
    row.correct_json = json.dumps(values["correct"])
    row.explanation = values["explanation"]
    row.source_quote = values.get("source_quote") or RULE_SOURCE_QUOTES.get(
        values["rule"], ""
    )
    row.updated_at = utcnow()
    row.updated_by = str(actor_id) if actor_id else None
    return row


def ensure_server_rule_questions(db):
    """Seed the built-in questions once; later edits live only in the database."""
    if db.query(ServerRuleQuestion.id).first() is not None:
        return
    stamp = utcnow()
    for item in SERVER_RULE_QUESTIONS:
        row = ServerRuleQuestion(
            id=item["id"],
            position=item["id"],
            created_at=stamp,
            updated_at=stamp,
        )
        apply_question(row, item)
        row.updated_by = None
        db.add(row)
    db.flush()


def list_server_rule_questions(db):
    ensure_server_rule_questions(db)
    return [
        question_record(row)
        for row in db.query(ServerRuleQuestion)
        .order_by(ServerRuleQuestion.position, ServerRuleQuestion.id)
        .all()
    ]
